const axios = require('axios');
const mongoose = require('mongoose');
require('dotenv').config();

const API_URL = 'http://localhost:5000/api';
const User = require('./models/User');

let token = '';
let projectId = '';
let apiKey = '';
let resetToken = '';
let logId = '';

const testUser = {
  name: "Acceptance Test User",
  email: `test_${Date.now()}@test.com`,
  password: "password123"
};

const runTests = async () => {
  console.log("=== MANUAL ACCEPTANCE TEST ===");
  
  // Connect DB for Reset Token grab
  await mongoose.connect(process.env.MONGODB_URI, { family: 4 });

  // 1. Register
  try {
    const res = await axios.post(`${API_URL}/auth/register`, testUser);
    console.log("1. Register: PASS -", res.data.data.email);
    token = res.data.token;
  } catch (e) {
    console.log("1. Register: FAIL -", e.response?.data || e.message);
  }

  // 2. Login
  try {
    const res = await axios.post(`${API_URL}/auth/login`, {
      email: testUser.email,
      password: testUser.password
    });
    console.log("2. Login: PASS -", "Token Received");
    token = res.data.token;
  } catch (e) {
    console.log("2. Login: FAIL -", e.response?.data || e.message);
  }

  // 3. Forgot Password
  try {
    const res = await axios.post(`${API_URL}/auth/forgot-password`, { email: testUser.email });
    console.log("3. Forgot Password: PASS -", res.data.message);
    
    // Grab reset token
    const user = await User.findOne({ email: testUser.email });
    // This isn't the raw token, it's hashed in the DB.
    // To actually reset, we need the raw token generated by crypto.
    // I will mock this by generating a new one directly using the method.
    resetToken = user.getResetPasswordToken();
    await user.save();
    
  } catch (e) {
    console.log("3. Forgot Password: FAIL -", e.response?.data || e.message);
  }

  // 4. Reset Password
  try {
    const res = await axios.post(`${API_URL}/auth/reset-password/${resetToken}`, { password: "newpassword123" });
    console.log("4. Reset Password: PASS -", "Password updated successfully");
    // Re-login with new password to get fresh token
    const loginRes = await axios.post(`${API_URL}/auth/login`, { email: testUser.email, password: "newpassword123" });
    token = loginRes.data.token;
  } catch (e) {
    console.log("4. Reset Password: FAIL -", e.response?.data || e.message);
  }

  const authHeader = { headers: { Authorization: `Bearer ${token}` } };

  // 5. Create Project
  try {
    const res = await axios.post(`${API_URL}/projects`, {
      name: "Acceptance Test Project",
      description: "Testing API key generation",
      databaseType: "PostgreSQL"
    }, authHeader);
    projectId = res.data.data._id;
    apiKey = res.data.data.apiKey;
    console.log("5. Create Project: PASS -", projectId);
  } catch (e) {
    console.log("5. Create Project: FAIL -", e.response?.data || e.message);
  }

  // 6. Generate API Key
  if (apiKey) {
    console.log("6. Generate API Key: PASS -", apiKey);
  } else {
    console.log("6. Generate API Key: FAIL - Not generated");
  }

  // 7. Regenerate API Key
  try {
    const res = await axios.post(`${API_URL}/projects/${projectId}/regenerate-key`, {}, authHeader);
    apiKey = res.data.data.apiKey; // update with new key
    console.log("7. Regenerate API Key: PASS -", apiKey);
  } catch (e) {
    console.log("7. Regenerate API Key: FAIL -", e.response?.data || e.message);
  }

  // 8. Analyze Safe Query
  try {
    const res = await axios.post(`${API_URL}/analyze-query`, {
      query: "SELECT username, email FROM users WHERE active = true",
      databaseType: "PostgreSQL",
      projectApiKey: apiKey
    });
    console.log("8. Analyze Safe Query: PASS -", res.data.data.status);
  } catch (e) {
    console.log("8. Analyze Safe Query: FAIL -", e.response?.data || e.message);
  }

  // 9. Analyze SQL Injection Query
  try {
    const res = await axios.post(`${API_URL}/analyze-query`, {
      query: "DROP TABLE users; --",
      databaseType: "PostgreSQL",
      projectApiKey: apiKey
    });
    console.log("9. Analyze SQL Injection Query: PASS -", res.data.data.status, "Risk:", res.data.data.risk);
  } catch (e) {
    console.log("9. Analyze SQL Injection Query: FAIL -", e.response?.data || e.message);
  }

  // 10. View Dashboard
  try {
    const res = await axios.get(`${API_URL}/dashboard/stats`, authHeader);
    console.log("10. View Dashboard: PASS - Total Requests:", res.data.data.totalRequests);
  } catch (e) {
    console.log("10. View Dashboard: FAIL -", e.response?.data || e.message);
  }

  // 11. View Logs
  try {
    const res = await axios.get(`${API_URL}/logs`, authHeader);
    console.log("11. View Logs: PASS - Found", res.data.data.length, "logs");
  } catch (e) {
    console.log("11. View Logs: FAIL -", e.response?.data || e.message);
  }

  // 12. Search Logs
  try {
    const res = await axios.get(`${API_URL}/logs?search=DROP`, authHeader);
    console.log("12. Search Logs: PASS - Found", res.data.data.length, "logs matching 'DROP'");
  } catch (e) {
    console.log("12. Search Logs: FAIL -", e.response?.data || e.message);
  }

  // 13. Filter Logs
  try {
    const res = await axios.get(`${API_URL}/logs?risk=critical`, authHeader);
    console.log("13. Filter Logs: PASS - Found", res.data.data.length, "critical logs");
  } catch (e) {
    console.log("13. Filter Logs: FAIL -", e.response?.data || e.message);
  }

  // 14. Logout
  try {
    const res = await axios.post(`${API_URL}/auth/logout`, {}, authHeader);
    console.log("14. Logout: PASS -", res.data.message);
  } catch (e) {
    console.log("14. Logout: FAIL -", e.response?.data || e.message);
  }

  // 15. Login Again
  try {
    const res = await axios.post(`${API_URL}/auth/login`, {
      email: testUser.email,
      password: "newpassword123"
    });
    console.log("15. Login Again: PASS - New Token Received");
  } catch (e) {
    console.log("15. Login Again: FAIL -", e.response?.data || e.message);
  }

  await mongoose.disconnect();
};

runTests();
